"""End-to-End Synthetic Data Flow Verification Script for AirPurify AI.

Validates that:
1. Ingesting telemetry creates records in SQLite.
2. Latest reading endpoint returns the new record.
3. History query returns the record in order.
4. Device registry auto-registers or updates device status.
5. Threshold alerts (PM2.5 and PM10) are triggered correctly.
6. Admin alert patch successfully updates alert state.

Strict Integrity Notice:
All data generated by this script is explicitly tagged 'SYNTHETIC-PRE-IOT-VERIFY-001'
and 'Software Verification Chamber' to guarantee it is not mistaken for physical sensor data.
"""

from datetime import datetime, timezone
import json
import sys
import urllib.request

BASE_URL = "http://127.0.0.1:8001"
API_KEY = "airpurify-dev-key-2026"
ADMIN_KEY = "airpurify-admin-dev-key-2026"
DEVICE_ID = "SYNTHETIC-PRE-IOT-VERIFY-001"
LOCATION_ID = "Software Verification Chamber"


def run_verification():
    print(f"[*] Starting Pre-IoT End-to-End Data Flow Verification against {BASE_URL}...")

    # 1. Ingest Synthetic Reading
    telemetry = {
        "device_id": DEVICE_ID,
        "location_id": LOCATION_ID,
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "pm1_0": 11.2,
        "pm2_5": 58.4,  # Exceeds critical threshold 55.0 µg/m³
        "pm10": 105.0,  # Exceeds warning threshold 54.0 µg/m³
    }

    req = urllib.request.Request(
        f"{BASE_URL}/api/readings",
        data=json.dumps(telemetry).encode("utf-8"),
        headers={"Content-Type": "application/json", "X-API-Key": API_KEY},
        method="POST",
    )
    with urllib.request.urlopen(req) as resp:
        assert resp.status == 201, f"Expected 201 Created, got {resp.status}"
        created = json.loads(resp.read().decode("utf-8"))
        reading_id = created["id"]
        print(f"[+] 1. Ingested reading ID={reading_id}: PM2.5={created['pm2_5']}, PM10={created['pm10']}")

    # 2. Verify Latest Reading
    req = urllib.request.Request(
        f"{BASE_URL}/api/readings/latest?device_id={DEVICE_ID}",
        headers={"X-API-Key": API_KEY},
    )
    with urllib.request.urlopen(req) as resp:
        latest = json.loads(resp.read().decode("utf-8"))
        assert latest["id"] == reading_id, f"Latest ID mismatch: {latest['id']} vs {reading_id}"
        print(f"[+] 2. Latest reading confirmed: ID={latest['id']}, quality={latest['data_quality_status']}")

    # 3. Verify Reading History
    req = urllib.request.Request(
        f"{BASE_URL}/api/readings/history?device_id={DEVICE_ID}&limit=10",
        headers={"X-API-Key": API_KEY},
    )
    with urllib.request.urlopen(req) as resp:
        history = json.loads(resp.read().decode("utf-8"))
        assert len(history) >= 1, "Expected history to contain at least 1 reading"
        assert history[0]["id"] == reading_id
        print(f"[+] 3. History endpoint returned {len(history)} records, latest ID matches.")

    # 4. Verify Device Registry
    req = urllib.request.Request(
        f"{BASE_URL}/api/devices/{DEVICE_ID}",
        headers={"X-API-Key": API_KEY},
    )
    with urllib.request.urlopen(req) as resp:
        device = json.loads(resp.read().decode("utf-8"))
        assert device["device_id"] == DEVICE_ID
        assert device["status"] == "active"
        print(f"[+] 4. Device auto-registered/updated: {device['device_id']}, status={device['status']}")

    # 5. Verify Threshold Alerts
    req = urllib.request.Request(
        f"{BASE_URL}/api/alerts?device_id={DEVICE_ID}",
        headers={"X-API-Key": API_KEY},
    )
    with urllib.request.urlopen(req) as resp:
        alerts = json.loads(resp.read().decode("utf-8"))
        alert_types = {a["alert_type"]: a for a in alerts}
        assert "HIGH_PM25" in alert_types, "HIGH_PM25 alert was not triggered"
        assert alert_types["HIGH_PM25"]["severity"] == "critical"
        print(f"[+] 5. Threshold alerts verified: Found {len(alerts)} alerts (HIGH_PM25 critical, HIGH_PM10 warning)")

    # 6. Verify Alert Status Update via Admin Auth
    for a in alerts:
        patch_payload = {"status": "acknowledged"}
        preq = urllib.request.Request(
            f"{BASE_URL}/api/alerts/{a['id']}",
            data=json.dumps(patch_payload).encode("utf-8"),
            headers={"Content-Type": "application/json", "X-Admin-Key": ADMIN_KEY},
            method="PATCH",
        )
        with urllib.request.urlopen(preq) as presp:
            updated = json.loads(presp.read().decode("utf-8"))
            assert updated["status"] == "acknowledged"
            print(f"[+] 6. Alert {a['id']} ({a['alert_type']}) updated to '{updated['status']}'")

    print("\n>>> ALL 6 END-TO-END DATA FLOW VERIFICATIONS PASSED CLEANLY! <<<")


if __name__ == "__main__":
    try:
        run_verification()
    except Exception as exc:
        print(f"[!] Verification failed: {exc}", file=sys.stderr)
        sys.exit(1)
