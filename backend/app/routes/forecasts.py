"""API routes for air quality predictive forecasting using MongoDB Atlas."""

from typing import Any, Dict, List, Optional
from datetime import datetime
from fastapi import APIRouter, Depends, Query, HTTPException, status
from pymongo.database import Database

from app.auth import require_admin_auth
from app.database import get_db, get_next_sequence_value
from app.models import Forecast
from app.rate_limiter import rate_limit, inference_rate_limiter
from app.schemas import ForecastPredictRequest, ForecastResponse, ForecastStatusResponse
from app.services.forecasting import forecasting_service

router = APIRouter(prefix="/api/forecasts", tags=["Forecasts"])


@router.get(
    "/status",
    response_model=ForecastStatusResponse,
    summary="Get forecasting model engine status",
    description="Check the operational and training readiness of the deep learning model.",
)
def get_model_status() -> dict:
    """Return status of the 1D-CNN–BiGRU forecasting model."""
    return forecasting_service.get_status()


@router.get(
    "",
    response_model=List[ForecastResponse],
    summary="Get forecast records",
    description="Retrieve forecasts generated by predictive models.",
)
def get_forecasts(
    location_id: Optional[str] = Query(None, description="Filter by location identifier"),
    db: Database = Depends(get_db),
) -> List[Forecast]:
    """Retrieve saved forecasts.

    Returns an empty list when no saved forecasts exist or model is unconfigured.
    """
    query = {}
    if location_id:
        query["location_id"] = location_id

    cursor = db["forecasts"].find(query).sort("target_time", 1)
    return [Forecast.from_mongo(doc) for doc in cursor]


@router.post(
    "/predict",
    summary="Generate on-demand deep learning forecast",
    description="Run inference using the 1D-CNN–BiGRU model for a specific location.",
)
def predict_forecast(
    request: ForecastPredictRequest,
    save_to_db: bool = Query(True, description="Whether to persist generated predictions to DB"),
    db: Database = Depends(get_db),
    _admin: str = Depends(require_admin_auth),
    _rate_check: None = Depends(rate_limit(inference_rate_limiter)),
) -> Dict[str, Any]:
    """Run model inference and return forecast result."""
    if not forecasting_service.is_configured:
        # Check if artifacts exist on disk and attempt on-demand load
        loaded = forecasting_service.load_artifacts()
        if not loaded:
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Forecasting model is not configured. Train or deploy weights first.",
            )

    forecast_data = forecasting_service.generate_forecast(
        location_id=request.location_id,
        horizon_hours=request.horizon_hours,
        recent_pm25_sequence=request.recent_pm25_sequence,
    )

    if save_to_db and forecast_data.get("predictions"):
        now_dt = datetime.fromisoformat(forecast_data["issued_at"])
        for p in forecast_data["predictions"]:
            f_seq = get_next_sequence_value(db, "forecasts_id")
            doc = {
                "id": f_seq,
                "location_id": request.location_id,
                "model_name": forecast_data["model_name"],
                "model_version": forecast_data["model_version"],
                "issued_at": now_dt,
                "target_time": datetime.fromisoformat(p["target_time"]),
                "horizon_hours": p["horizon_hours"],
                "predicted_aqi": p["predicted_aqi"],
                "predicted_pm25": p["predicted_pm25"],
                "predicted_pm10": p["predicted_pm10"],
                "confidence_interval_lower": p["confidence_interval_lower"],
                "confidence_interval_upper": p["confidence_interval_upper"],
                "status": p["status"],
            }
            db["forecasts"].insert_one(doc)

    return forecast_data
